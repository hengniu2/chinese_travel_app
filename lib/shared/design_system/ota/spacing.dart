/// OTA Design System — Spacing (8px grid)
/// All spacing is a multiple of 8 for alignment and rhythm
class OtaSpacing {
  OtaSpacing._();

  /// 8px
  static const double xxs = 8;

  /// 16px
  static const double xs = 16;

  /// 24px
  static const double sm = 24;

  /// 32px
  static const double md = 32;

  /// 40px
  static const double lg = 40;

  /// 48px
  static const double xl = 48;

  /// 56px
  static const double xxl = 56;

  /// 64px
  static const double xxxl = 64;

  // ─────────────────────────────────────────────────────────────────────────
  // Semantic
  // ─────────────────────────────────────────────────────────────────────────
  /// Screen horizontal padding
  static const double screenHorizontal = xs;

  /// Between sections
  static const double sectionGap = md;

  /// Between list items / card gaps
  static const double itemGap = xs;

  /// Inline / within component
  static const double inline = xxs;
}
